const byLabel = new Map(Object.entries(messages).map(([key, value]) => [value, key]));
export function recordedNotesLabel(count) { return beatEnglish('app.music.beat.status.s84', { p0: count }); }
export function actionLabel(label, t = beatEnglish) {
  const notes = /^Recorded (\d+) notes$/.exec(label);
  if (notes) return t('app.music.beat.status.s84', { p0: notes[1] });
  return byLabel.has(label) ? t(byLabel.get(label)) : beatText(label, t); }
