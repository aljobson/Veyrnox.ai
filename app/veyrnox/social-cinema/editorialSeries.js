const YOUTUBE_VIDEO_ID = /^[A-Za-z0-9_-]{11}$/;
const youtubePoster = (videoId, quality = 'hqdefault') =>
  `https://i.ytimg.com/vi/${videoId}/${quality}.jpg`;

const youtubeEpisode = (slug, position, title, videoId, durationSeconds) => Object.freeze({
  id: `${slug}-${String(position).padStart(2, '0')}`,
  position,
  title,
  description: '',
  durationSeconds,
  posterUrl: youtubePoster(videoId),
  playback: Object.freeze({
    provider: 'youtube',
    videoId,
    startSeconds: 0,
    endSeconds: durationSeconds,
  }),
});

const youtubeSeries = ({
  slug,
  title,
  season = 1,
  seasonTitle,
  description,
  posterVideoId,
  categories,
  creatorName,
  creatorChannelId,
  sourceUrl,
  episodes,
}) => Object.freeze({
  slug,
  title,
  season,
  seasonTitle,
  description,
  posterUrl: youtubePoster(posterVideoId),
  categories: Object.freeze(categories),
  creator: Object.freeze({
    name: creatorName,
    url: `https://www.youtube.com/channel/${creatorChannelId}`,
  }),
  source: Object.freeze({
    name: 'YouTube',
    url: sourceUrl,
    method: 'embed',
  }),
  episodes: Object.freeze(episodes.map(([episodeTitle, videoId, durationSeconds], index) =>
    youtubeEpisode(slug, index + 1, episodeTitle, videoId, durationSeconds))),
});

