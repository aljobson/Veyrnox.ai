import { act } from 'react';
import * as RN from 'react-native';
import { createRoot, type Root } from 'test-renderer';
import { ChatText, shareReplyLink } from '../src/components/chat/ChatText';
import { MessageBubble } from '../src/components/chat/MessageBubble';
import { t } from '../src/lib/i18n';
void [RN.View, RN.Text, RN.ScrollView, RN.Pressable];
let root: Root;
beforeEach(() => { (globalThis as any).IS_REACT_ACT_ENVIRONMENT = true; root = createRoot(); jest.clearAllMocks(); });
afterEach(async () => { await act(async () => root.unmount()); });
test('headings, lists, inline formatting, safe links and code sharing', async () => {
    const share = jest.spyOn(RN.Share, 'share').mockResolvedValue({ action: RN.Share.sharedAction, activityType: undefined });
    await act(async () => root.render(<ChatText content={'# Heading\n\n- one\n- **two**\n\n1. first\n\n`inline` [site](https://EXAMPLE.com)\n\n```js\nconst x = 1\n```'} />));
    const heading = root.container.queryAll(n => n.children.includes('Heading'))[0];
    expect(RN.StyleSheet.flatten(heading.props.style).fontWeight).toBe('700'); expect(heading.props.accessibilityRole).not.toBe('header');
    expect(root.container.queryAll(n => n.children.includes('• ')).length).toBe(2);
    expect(root.container.queryAll(n => n.children.includes('1. '))).toHaveLength(1);
    expect(root.container.queryAll(n => n.props.horizontal && n.props.keyboardShouldPersistTaps === 'handled')).toHaveLength(1);
    const link = root.container.queryAll(n => n.props.accessibilityRole === 'link')[0];
    await act(async () => link.props.onPress());
    expect(share).toHaveBeenCalledTimes(1); expect(share).toHaveBeenCalledWith({ message: 'https://example.com/' });
    expect(link.props.accessibilityLabel).toBe('Copy or share site');
    await shareReplyLink('javascript:alert(1)'); await shareReplyLink('https://user:pw@example.com');
    expect(share).toHaveBeenCalledTimes(1);
    const copy = root.container.queryAll(n => n.props.accessibilityLabel === t('chatDepth.copyCode'))[0];
    await act(async () => copy.props.onClick({ nativeEvent: {} })); expect(share).toHaveBeenCalledWith({ message: 'const x = 1' }); share.mockRestore();
});
test('accessible reply group remains a direct bubble child with link and code actions', async () => {
    const content = '[one](https://one.example) [two](https://two.example)\n```\ncode';
    const share = jest.spyOn(RN.Share, 'share').mockResolvedValue({ action: RN.Share.sharedAction, activityType: undefined });
    await act(async () => root.render(<MessageBubble message={{ id: 'a', role: 'assistant', content }} sending drafts={[]} />));
    const group = root.container.queryAll(n => n.props.accessibilityLabel === `Assistant: ${content}`)[0];
    expect(group.props.accessible).toBe(true); expect(RN.StyleSheet.flatten(group.parent!.props.style).borderRadius).toBe(20);
    expect(group.props.accessibilityActions.map((a: any) => a.name)).toEqual(['link-0', 'link-1', 'code-0']);
    await act(async () => group.props.onAccessibilityAction({ nativeEvent: { actionName: 'link-1' } }));
    expect(share).toHaveBeenCalledWith({ message: 'https://two.example/' });
    expect(group.props.accessibilityActions[1].label).toBe('Copy or share two');
    await act(async () => group.props.onAccessibilityAction({ nativeEvent: { actionName: 'code-0' } })); expect(share).toHaveBeenCalledWith({ message: 'code' }); share.mockRestore();
});
