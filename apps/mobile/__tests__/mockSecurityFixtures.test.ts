declare const require: (name: string) => any;
declare const __dirname: string;
const { execFileSync } = require('node:child_process');
const path = require('node:path');

test('opt-in dev security fixtures exercise real endpoint shapes and fixed-code state transitions', () => {
    const fixturePath = path.resolve(__dirname, '../dev/mockSecurityFixtures.mjs');
    const output = execFileSync(process.execPath, ['--input-type=module', '-e', `
        import assert from 'node:assert/strict';
        import { securityFixturesEnabled, createSecurityFixtures, securityResponse, SECURITY_SECRET, SECURITY_URI } from ${JSON.stringify(fixturePath)};
        assert.equal(securityFixturesEnabled({}), false);
        assert.equal(securityFixturesEnabled({ MOCK_SECURITY_FIXTURES: '1' }), true);
        assert.equal(securityFixturesEnabled({ MOCK_SECURITY_FIXTURES: '1', NODE_ENV: 'production' }), false);
        const s = createSecurityFixtures();
        const call = (method, path, body) => securityResponse(s, method, new URL(path, 'http://localhost'), body);
        assert.equal(s.factors.length, 1);
        assert.equal(s.passkeys.length, 2);
        assert.equal(s.devices.length, 2);
        assert.equal(s.grants.length, 1);
        assert.equal(call('GET', '/auth/v1/user').body.factors[0].status, 'verified');
        assert.equal(call('GET', '/auth/v1/passkeys').body.passkeys.length, 2);
        call('DELETE', '/auth/v1/passkeys/mock_key_phone');
        assert.equal(s.passkeys.length, 1);
        const challenge = call('POST', '/auth/v1/factors/mock-totp/challenge').body.id;
        assert.equal(call('POST', '/auth/v1/factors/mock-totp/verify', { challenge_id: challenge, code: '654321' }).status, 400);
        const verified = call('POST', '/auth/v1/factors/mock-totp/verify', { challenge_id: challenge, code: '123456' }).body;
        const payload = JSON.parse(Buffer.from(verified.access_token.split('.')[1], 'base64url'));
        assert.equal(payload.aal, 'aal2');
        const refresh = call('POST', '/auth/v1/token', { refresh_token: verified.refresh_token }).body;
        assert.equal(JSON.parse(Buffer.from(refresh.access_token.split('.')[1], 'base64url')).aal, 'aal2');
        call('DELETE', '/auth/v1/factors/mock-totp');
        assert.equal(s.factors.length, 0);
        const enrolled = call('POST', '/auth/v1/factors', { friendly_name: 'My authenticator', factor_type: 'totp' }).body;
        assert.equal(enrolled.totp.secret, SECURITY_SECRET);
        assert.equal(enrolled.totp.uri, SECURITY_URI);
        assert.equal(s.factors[0].status, 'unverified');
        const next = call('POST', '/auth/v1/factors/mock-enrolment/challenge').body.id;
        assert.equal(call('POST', '/auth/v1/factors/mock-enrolment/verify', { challenge_id: next, code: '123456' }).status, 200);
        assert.equal(s.factors[0].status, 'verified');
        call('DELETE', '/auth/v1/user/oauth/grants?client_id=11111111-1111-4111-8111-111111111111');
        assert.equal(call('GET', '/auth/v1/user/oauth/grants').body.grants.length, 0);
        call('POST', '/auth/v1/logout?scope=others');
        assert.deepEqual(s.devices.map(d => d.id), ['mock-phone']);
        call('POST', '/auth/v1/logout?scope=global');
        assert.equal(s.devices.length, 0);
        assert.equal(call('GET', '/unrelated'), null);
        assert.equal(createSecurityFixtures().passkeys.length, 2);
        console.log('Security fixture endpoint checks passed');
    `], { encoding: 'utf8' });
    expect(output).toContain('Security fixture endpoint checks passed');
});
