// Spike B1: bundle the real beat engine into one HTML page and write it into src/lib/beatEngineSpikeHtml.ts.
// Dev only. The committed file is an empty stub so no release bundle carries the engine; run this to fill it,
// and `git checkout src/lib/beatEngineSpikeHtml.ts` before committing.
// ESBUILD_PATH lets a source-only checkout use another checkout's esbuild (this app has no install of its own).
const { build } = await import(process.env.ESBUILD_PATH || 'esbuild');
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const mobile = path.resolve(here, '..');
const result = await build({
    entryPoints: [path.join(here, 'beat-spike/entry.js')],
    bundle: true, format: 'iife', write: false, minify: true, target: 'safari15', loader: { '.js': 'js' },
    plugins: [{ name: 'worklet-text', setup(b) { b.onLoad({ filter: /beat-capture-worklet\.js$/ }, (a) => ({ contents: readFileSync(a.path, 'utf8'), loader: 'text' })); } }],
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,user-scalable=no">
<style>body{margin:0;background:#0b0b10;color:#e8e8f0;font:14px -apple-system,sans-serif;padding:12px}button{font:inherit;min-height:48px;margin:4px;padding:0 14px;border-radius:10px;border:1px solid #556;background:#1a1a24;color:#fff}
#pad{width:100%;height:120px;font-size:20px;background:#3a2a6a}pre{white-space:pre-wrap;font-size:12px;color:#9fd}</style></head>
<body><button id="pad">PAD (web tap)</button><div><button id="start">Start 8 tracks</button><button id="stop">Stop</button><button id="caps">Capabilities</button><button id="mic">Mic probe</button></div><pre id="out">ready</pre>
<script>${js}</script></body></html>`;
const target = path.join(mobile, 'src/lib/beatEngineSpikeHtml.ts');
writeFileSync(target, `// GENERATED by scripts/build-beat-spike.mjs. Do not commit the generated body.\nexport const BEAT_SPIKE_HTML: string = ${JSON.stringify(html)};\n`);
console.log(`wrote ${target} (${(html.length / 1024).toFixed(0)} KB)`);
