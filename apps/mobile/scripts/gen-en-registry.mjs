#!/usr/bin/env node
// Run from apps/mobile. The directory, not this registry, owns the list of areas.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const messages = resolve(dirname(fileURLToPath(import.meta.url)), '../src/lib/i18n/messages');
export function areaNames(directory = join(messages, 'en')) {
    return readdirSync(directory).filter(name => !name.startsWith('_') && name.endsWith('.ts')).sort().map(name => {
        const area = name.slice(0, -3);
        if (!/^[a-zA-Z][a-zA-Z0-9]*$/.test(area)) throw new Error(`Invalid area filename: ${name}`);
        return area;
    });
}
export function renderRegistry(directory = join(messages, 'en')) {
    const areas = areaNames(directory);
    return `// Generated by node scripts/gen-en-registry.mjs. Do not edit; rerun it to resolve conflicts.
// Area = prefix before the first dot. _order preserves historical enumeration; never add keys there.
// Generate the ignored localization list with node scripts/sync-web-i18n.mjs (from apps/mobile).
import order from './en/_order';
${areas.map(area => `import area_${area} from './en/${area}';`).join('\n')}

const catalog = {
${areas.map(area => `    ...area_${area},`).join('\n')}
} as const;

const historical = new Set<string>(order);
const keys = [
    ...order.filter(key => Object.prototype.hasOwnProperty.call(catalog, key)),
    ...Object.keys(catalog).filter(key => !historical.has(key)),
];
const en = Object.fromEntries(keys.map(key => [key, catalog[key as keyof typeof catalog]])) as typeof catalog;
export default en;
`;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const output = join(messages, 'en.ts');
    const expected = renderRegistry();
    if (process.argv.includes('--check')) {
        if (readFileSync(output, 'utf8') !== expected) {
            console.error('English registry is stale. Run node scripts/gen-en-registry.mjs');
            process.exitCode = 1;
        } else console.log('English registry is current.');
    } else {
        writeFileSync(output, expected);
        console.log('Wrote English registry.');
    }
}
