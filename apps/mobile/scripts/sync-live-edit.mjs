// Pure engine only: Metro never traverses the web app's React/node_modules.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const source = new URL('../../../packages/live-edit/', import.meta.url);
const target = new URL('../src/lib/liveEdit/shared/', import.meta.url);
mkdirSync(target, { recursive: true });
for (const name of ['effects', 'makeup', 'hair', 'regions', 'looks', 'smoothing', 'wigs', 'wigFit', 'wig3d']) {
    const body = readFileSync(new URL(`${name}.js`, source), 'utf8');
    const path = new URL(`${name}.js`, target);
    if (process.argv.includes('--check')) {
        if (readFileSync(path, 'utf8') !== body) throw Error(`Live Edit parity: ${name}`);
    } else writeFileSync(path, body);
}
// The six original wig SVGs ship inside the app as pre-rendered PNGs in one generated module, so no network, file URL or SVG
// parser is involved at run time (and software Skia in tests can decode them). Each entry records the SHA-256 of the SVG it was
// rendered from; --check verifies those against the manifest in wigs.js without re-rendering (PNG bytes vary with the rasteriser).
const { createHash } = await import('node:crypto');
const { createRequire } = await import('node:module');
const { WIGS } = await import(new URL('wigs.js', source));
const assetPath = new URL('wigAssets.js', target), WIG_PIXELS = [1024, 1280];
if (process.argv.includes('--check')) {
    const { WIG_PNG } = await import(assetPath);
    for (const wig of WIGS) {
        const entry = WIG_PNG[wig.id];
        if (!entry || entry.svgSha256 !== wig.sha256 || entry.width !== WIG_PIXELS[0] || entry.height !== WIG_PIXELS[1] || !entry.base64) throw Error(`Live Edit parity: wigAssets ${wig.id} is stale; run node scripts/sync-live-edit.mjs`);
    }
    if (Object.keys(WIG_PNG).length !== WIGS.length) throw Error('Live Edit parity: wigAssets has extra entries');
} else {
    const sharp = createRequire(import.meta.url)('../../../node_modules/sharp');
    const art = {};
    for (const wig of WIGS) {
        const svg = readFileSync(new URL(`../../../public${wig.file}`, import.meta.url));
        if (createHash('sha256').update(svg).digest('hex') !== wig.sha256) throw Error(`Live Edit wig art does not match its manifest hash: ${wig.id}`);
        const png = await sharp(svg, { density: 72 * WIG_PIXELS[0] / wig.dimensions[0] }).resize(WIG_PIXELS[0], WIG_PIXELS[1]).png({ compressionLevel: 9, adaptiveFiltering: true }).toBuffer();
        art[wig.id] = { svgSha256: wig.sha256, width: WIG_PIXELS[0], height: WIG_PIXELS[1], base64: png.toString('base64') };
    }
    writeFileSync(assetPath, `// Generated by apps/mobile/scripts/sync-live-edit.mjs from public/photo-studio/wigs. Do not edit by hand.\nexport const WIG_PNG = Object.freeze(${JSON.stringify(art)});\n`);
}
console.log(`Live Edit shared engine ${process.argv.includes('--check') ? 'verified' : 'synced'}: ${fileURLToPath(target)}`);
