// Writes src/lib/oddlings/cast.json from the web's Oddlings cast, so the phone shows the same 72 original characters
// without copying 600 lines of data by hand. `--check` fails when the file is out of date (the drift test runs it).
// Plain Node, no dependencies: it imports the web files by relative path.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '..', '..', '..', 'app', 'veyrnox', '_lib');
const character = await import(join(web, 'character.js'));
const options = await import(join(web, 'characterOptions.js'));
const studio = await import(join(web, 'oddlingStudio.js'));
const explore = await import(join(web, 'oddlingExplore.js'));
const catalog = await import(join(web, 'oddlingCatalog.js'));

const note = (table, label) => (table.find(([name]) => name === label) || [])[1] || '';
const tabs = explore.ODDLING_EXPLORE_TABS.map(({ id, label }) => ({ id, label }));
const inTab = (id, tab) => studio.oddlingsForSource(tab).some((item) => item.id === id);

const characters = character.ODDLING_ARCHETYPES.map((item) => {
  const picks = item.picks || {};
  return {
    id: item.id,
    kind: item.kind,
    name: item.name,
    hook: item.hook,
    accent: item.accent,
    collections: tabs.filter(({ id }) => id !== 'all' && inTab(item.id, id)).map(({ id }) => id),
    premise: {
      obsession: picks.oddling_obsession || '',
      voice: picks.oddling_voice || '',
      voiceNote: note(character.ODDLING_TONES, picks.oddling_voice),
      show: picks.oddling_show || '',
      showNote: note(character.ODDLING_SHOWS, picks.oddling_show),
    },
    identity: character.oddlingIdentity(picks),
    traits: character.CHARACTER_GROUPS.flatMap((group) => (picks[group.id] ? [`${group.label}: ${options.characterOptionLabel(group.id, picks[group.id])}`] : [])),
    picks,
  };
});

// One character per line keeps the file small and a diff readable.
const out = `{"generatedFrom":"app/veyrnox/_lib/character.js","tabs":${JSON.stringify(tabs)},"heroes":${JSON.stringify(explore.ODDLING_HERO_IDS)},"characters":[\n${characters.map((c) => JSON.stringify(c)).join(',\n')}\n]}\n`;

// The builder's data: every group with its options (value, prompt phrase, display label), the voices and shows, the
// studio sections, motions and scenes. The logic that uses it is ported by hand in src/lib/oddlingsBuilder.ts and a
// test compares its prompts with the web's.
const builder = {
  base: character.CHARACTER_BASE,
  tabs: character.CHARACTER_TABS,
  tones: character.ODDLING_TONES,
  shows: character.ODDLING_SHOWS,
  categories: catalog.CATALOG_CATEGORIES.map(({ id, label, hint, groupIds }) => ({ id, label, hint, groupIds })),
  focus: catalog.CATEGORY_FOCUS,
  swatches: catalog.SWATCHES,
  motions: studio.ODDLING_MOTIONS,
  scenes: studio.ODDLING_SCENES,
  groups: character.CHARACTER_GROUPS.map((g) => ({ id: g.id, tab: g.tab, label: g.label, options: g.options.map(([value, phrase]) => [value, phrase, options.characterOptionLabel(g.id, value)]) })),
};
const builderOut = `{${Object.entries(builder).map(([k, v]) => `${JSON.stringify(k)}:${k === 'groups' ? `[\n${v.map((g) => JSON.stringify(g)).join(',\n')}\n]` : JSON.stringify(v)}`).join(',\n')}}\n`;

// The preview figure. The web draws it from pure geometry (picks in, SVG shapes out); the app has no SVG library and may
// not add one, so the same modules are wrapped into one script that a WebView runs offline. Nothing is rewritten by hand.
const FIGURE_MODULES = ['oddlingColour', 'oddlingSkinFx', 'oddlingSpecies', 'oddlingFace', 'oddlingBodyParts', 'oddlingMannequin'];
const wrapModule = (name) => {
  const names = [];
  const body = readFileSync(join(web, `${name}.js`), 'utf8')
    .replace(/^import\s*\{([^}]*)\}\s*from\s*'\.\/(\w+)\.js';?$/gm, (_m, list, dep) => `const {${list}} = __m.${dep};`)
    .replace(/^export\s*\{([^}]*)\};?$/gm, (_m, list) => { names.push(...list.split(',').map((x) => x.trim()).filter(Boolean)); return ''; })
    .replace(/^export\s+(?:const|function|class)\s+(\w+)/gm, (m, id) => { names.push(id); return m.replace(/^export\s+/, ''); });
  if (/^\s*(?:import|export)\b/m.test(body)) throw new Error(`${name}.js uses module syntax the figure bundle cannot wrap`);
  return `__m.${name}=(()=>{\n${body}\nreturn {${names.join(',')}};})();`;
};
const figureScript = [`const __m={};`, `__m.oddlingCatalog={SWATCHES:${JSON.stringify(catalog.SWATCHES)}};`, ...FIGURE_MODULES.map(wrapModule), 'const __f=__m.oddlingMannequin;'].join('\n');
const figureOut = `// Generated by scripts/sync-oddlings-cast.mjs from the web's oddlingMannequin.js and the modules it uses. Do not edit.\nexport const FIGURE_SCRIPT = ${JSON.stringify(figureScript)};\n`;

const dir = join(here, '..', 'src', 'lib', 'oddlings');
const targets = [['cast.json', out], ['builder.json', builderOut], ['figureScript.ts', figureOut]];
const stale = [];
for (const [name, text] of targets) {
  let current = '';
  try { current = readFileSync(join(dir, name), 'utf8'); } catch { /* first run */ }
  if (current === text) continue;
  stale.push(name);
  if (!process.argv.includes('--check')) writeFileSync(join(dir, name), text);
}
if (process.argv.includes('--check') && stale.length) { console.error(`src/lib/oddlings/${stale.join(', ')} out of date. Run node scripts/sync-oddlings-cast.mjs`); process.exit(1); }
console.log(stale.length ? `Wrote ${stale.join(', ')}` : 'Up to date.');
