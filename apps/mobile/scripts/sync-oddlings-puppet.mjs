// Writes src/lib/oddlings/puppetScript.ts: the web's animated puppet (shader, pixel preparation, rigs and pose maths for
// the 72 cast portraits) wrapped, not rewritten, into one script that a WebView runs offline. `--check` fails when the
// file is out of date (the drift test runs it). Plain Node, no dependencies.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '..', '..', '..', 'app', 'veyrnox', '_lib');
const MODULES = ['oddlingFeatureRigs', 'oddlingPuppetRigs', 'oddlingPuppetRenderer'];

const wrapModule = (name) => {
  const names = [];
  const body = readFileSync(join(web, `${name}.js`), 'utf8')
    .replace(/^import\s*\{([^}]*)\}\s*from\s*'\.\/(\w+)\.js';?$/gm, (_m, list, dep) => `const {${list}} = __m.${dep};`)
    .replace(/^export\s*\{([^}]*)\};?$/gm, (_m, list) => { names.push(...list.split(',').map((x) => x.trim()).filter(Boolean)); return ''; })
    .replace(/^export\s+(?:const|function|class)\s+(\w+)/gm, (m, id) => { names.push(id); return m.replace(/^export\s+/, ''); });
  if (/^\s*(?:import|export)\b/m.test(body)) throw new Error(`${name}.js uses module syntax the puppet bundle cannot wrap`);
  return `__m.${name}=(()=>{\n${body}\nreturn {${names.join(',')}};})();`;
};

const script = [`const __m={};`, ...MODULES.map(wrapModule)].join('\n');
if (script.includes('</script')) throw new Error('the puppet bundle would end the page script early');
const out = `// Generated by scripts/sync-oddlings-puppet.mjs from the web's oddlingPuppetRenderer.js, oddlingPuppetRigs.js and oddlingFeatureRigs.js. Do not edit.\nexport const PUPPET_SCRIPT = ${JSON.stringify(script)};\n`;

const target = join(here, '..', 'src', 'lib', 'oddlings', 'puppetScript.ts');
let current = '';
try { current = readFileSync(target, 'utf8'); } catch { /* first run */ }
if (current === out) { console.log('Up to date.'); process.exit(0); }
if (process.argv.includes('--check')) { console.error('src/lib/oddlings/puppetScript.ts out of date. Run node scripts/sync-oddlings-puppet.mjs'); process.exit(1); }
writeFileSync(target, out);
console.log('Wrote puppetScript.ts');
