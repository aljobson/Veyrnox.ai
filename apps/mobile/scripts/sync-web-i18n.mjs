#!/usr/bin/env node
// Copies the public site's translations (lib/i18n/messages, ADR-0107) for the keys the app shares with it into
// src/lib/i18n/messages/<code>.ts, verbatim, and lists the app-only keys for the localization process.
// Nothing is translated here. Usage: node scripts/sync-web-i18n.mjs [--check]   (--check changes nothing and fails on drift)
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..');
const repo = join(app, '..', '..');
const WEB = join(repo, 'lib', 'i18n', 'messages');
const OUT = join(app, 'src', 'lib', 'i18n', 'messages');
const CODES = ['es', 'zh', 'hi', 'ar', 'fr', 'pt', 'ru', 'ja', 'de', 'ko'];
const check = process.argv.includes('--check');

// A catalog file is `export default { ... }` or `const x = { ... } as const; export default x;` with no imports.
function readCatalog(path) {
    const text = readFileSync(path, 'utf8').replace(/\bas const\b/g, '').replace(/^export default\s+/m, 'return ').replace(/^return (\w+);\s*$/m, 'return $1;');
    const m = { exports: undefined };
    return new Function('module', text.includes('return ') ? text : `module.exports = ${text}`)(m) ?? m.exports;
}

const webKeys = JSON.parse(readFileSync(join(OUT, '..', 'webKeys.json'), 'utf8'));
const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
const changed = [];

for (const code of CODES) {
    const web = readCatalog(join(WEB, `${code}.mjs`));
    const lines = [];
    const missing = [];
    for (const key of webKeys) {
        if (typeof web[key] === 'string') lines.push(`    ${q(key)}: ${q(web[key])},`);
        else missing.push(key);
    }
    const body = `// Generated by scripts/sync-web-i18n.mjs from the public site's ${code} catalog (ADR-0107). Do not edit by hand.\n// Only the keys the app shares with the site; every other key falls back to English until the localization process\n// returns the app-only strings (docs/mobile/I18N-NEW-KEYS.md).\nconst ${code} = {\n${lines.join('\n')}\n} as const;\n\nexport default ${code};\n`;
    const file = join(OUT, `${code}.ts`);
    let current = '';
    try { current = readFileSync(file, 'utf8'); } catch { /* new file */ }
    if (current !== body) { changed.push(relative(app, file)); if (!check) writeFileSync(file, body); }
    if (missing.length) console.log(`${code}: ${missing.length} key(s) not in the site catalog (English is used): ${missing.join(', ')}`);
}

// App-only keys for the localization process.
const en = readCatalog(join(OUT, 'en.ts'));
const used = (key) => {
    const hits = [];
    const walk = (dir) => {
        for (const e of readdirSync(dir, { withFileTypes: true })) {
            const p = join(dir, e.name);
            if (e.isDirectory()) walk(p);
            else if (/\.tsx?$/.test(e.name) && !p.includes('/messages/') && readFileSync(p, 'utf8').includes(`'${key.replace(/\.(one|other|few|many|two|zero)$/, '')}'`)) hits.push(relative(join(app, 'src'), p));
        }
    };
    walk(join(app, 'src'));
    return [...new Set(hits)].join(', ');
};
const rows = Object.entries(en).filter(([k]) => !webKeys.includes(k)).map(([k, v]) => `| \`${k}\` | ${String(v).replace(/\|/g, '\\|')} | ${used(k)} |`);
const doc = `# New strings for the localization process\n\nGenerated by \`node scripts/sync-web-i18n.mjs\`. These are the app-only keys in \`apps/mobile/src/lib/i18n/messages/en.ts\`: the public site has no translation for them, so no language is offered for them yet. Placeholders such as \`{count}\` must be kept as written; keys ending in \`.one\` and \`.other\` (and the other CLDR categories) are plural forms.\n\n${rows.length} keys.\n\n| Key | English | Used in |\n|---|---|---|\n${rows.join('\n')}\n`;
const docPath = join(repo, 'docs', 'mobile', 'I18N-NEW-KEYS.md');
let docCurrent = '';
try { docCurrent = readFileSync(docPath, 'utf8'); } catch { /* new file */ }
if (docCurrent !== doc) { changed.push(relative(repo, docPath)); if (!check) writeFileSync(docPath, doc); }

if (check && changed.length) { console.error(`Out of date: ${changed.join(', ')}. Run node scripts/sync-web-i18n.mjs`); process.exit(1); }
console.log(check ? 'Up to date.' : `Wrote ${changed.length} file(s).`);
