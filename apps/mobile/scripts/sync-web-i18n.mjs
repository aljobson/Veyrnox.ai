#!/usr/bin/env node
// Copies the public site's translations (lib/i18n/messages, ADR-0107) for the keys the app shares with it into
// src/lib/i18n/messages/<code>.ts, verbatim, and lists the app-only keys for the localization process.
// Nothing is translated here. Usage: node scripts/sync-web-i18n.mjs [--check]   (--check validates committed locale catalogs; the ignored report is checked in memory by Jest)
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { escapeCell } from './escape-cell.mjs';
import { areaNames } from './gen-en-registry.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const app = join(here, '..');
const repo = join(app, '..', '..');
const WEB = join(repo, 'lib', 'i18n', 'messages');
const OUT = join(app, 'src', 'lib', 'i18n', 'messages');
const CODES = ['es', 'zh', 'hi', 'ar', 'fr', 'pt', 'ru', 'ja', 'de', 'ko'];

// A catalog file is `export default { ... }` or `const x = { ... } as const; export default x;` with no imports.
function readCatalog(path) {
    // Skip strings/comments, and strip only the final object assertion (or _order.ts array assertion).
    const source = readFileSync(path, 'utf8');
    const tokens = /'(?:\\[\s\S]|[^'\\])*'|"(?:\\[\s\S]|[^"\\])*"|`(?:\\[\s\S]|[^`\\])*`|\/\/[^\r\n]*|\/\*[\s\S]*?\*\/|([}\]])\s+as const;/g;
    const trivia = String.raw`(?:\s|\/\/[^\r\n]*|\/\*[\s\S]*?\*\/)*`;
    const exportEnd = new RegExp(`^${trivia}(?:export default \\w+;${trivia})?$`);
    const text = source.replace(tokens, (match, closing, offset) =>
        closing && exportEnd.test(source.slice(offset + match.length)) ? `${closing};` : match
    ).replace(/^export default\s+/m, 'return ').replace(/^return (\w+);\s*$/m, 'return $1;');
    const m = { exports: undefined };
    return new Function('module', text.includes('return ') ? text : `module.exports = ${text}`)(m) ?? m.exports;
}

// Read data-only area catalogs without importing app/runtime code or evaluating en.ts.
export function readEnglishCatalog(directory = join(OUT, 'en')) {
    const catalog = {};
    for (const area of areaNames(directory)) {
        const file = join(directory, `${area}.ts`);
        let values;
        try {
            values = readCatalog(file);
        } catch (error) {
            throw new Error(`Failed to evaluate English area file ${file}: ${error instanceof Error ? error.message : String(error)}`, { cause: error });
        }
        for (const [key, value] of Object.entries(values)) {
            if (key.split('.')[0] !== area) throw new Error(`Wrong area for ${key}: ${area}`);
            if (Object.hasOwn(catalog, key)) throw new Error(`Duplicate English key: ${key}`);
            catalog[key] = value;
        }
    }
    const order = readCatalog(join(directory, '_order.ts'));
    const historical = new Set(order);
    return Object.fromEntries([
        ...order.filter(key => Object.hasOwn(catalog, key)),
        ...Object.keys(catalog).filter(key => !historical.has(key)),
    ].map(key => [key, catalog[key]]));
}

// Shared by the CLI and wiring test. Importing this module writes nothing.
export function buildAppOnlyRows(en, webKeys, used = () => '') {
    return Object.entries(en).filter(([key]) => !webKeys.includes(key))
        .map(([key, value]) => `| \`${key}\` | ${escapeCell(value)} | ${used(key)} |`);
}

export function syncWebI18n(check = false) {
    const webKeys = JSON.parse(readFileSync(join(OUT, '..', 'webKeys.json'), 'utf8'));
    const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
    const changed = [];

    for (const code of CODES) {
        const web = { ...readCatalog(join(WEB, `${code}.mjs`)),
            ...readCatalog(join(WEB, 'app', code, 'publish-composer.mjs')),
            ...readCatalog(join(WEB, 'app', code, 'publish.mjs')) };
        const lines = [];
        const missing = [];
        for (const key of webKeys) {
            if (typeof web[key] === 'string') lines.push(`    ${q(key)}: ${q(web[key])},`);
            else missing.push(key);
        }
        const body = `// Generated by scripts/sync-web-i18n.mjs from the public site's ${code} catalog (ADR-0107). Do not edit by hand.\n// Only the keys the app shares with the site; every other key falls back to English until the localization process\n// returns the app-only strings (generate the list: node scripts/sync-web-i18n.mjs).\nconst ${code} = {\n${lines.join('\n')}\n} as const;\n\nexport default ${code};\n`;
        const file = join(OUT, `${code}.ts`);
        let current = '';
        try { current = readFileSync(file, 'utf8'); } catch { /* new file */ }
        if (current !== body) { changed.push(relative(app, file)); if (!check) writeFileSync(file, body); }
        if (missing.length) console.log(`${code}: ${missing.length} key(s) not in the site catalog (English is used): ${missing.join(', ')}`);
    }

    // App-only keys for the localization process.
    const en = readEnglishCatalog();
    // Read each source once; then match literal callsites for each key (plural bases included).
    const sources = [];
    const walk = (dir) => {
        for (const entry of readdirSync(dir, { withFileTypes: true })) {
            const path = join(dir, entry.name);
            if (entry.isDirectory() && entry.name !== 'messages') walk(path);
            else if (entry.isFile() && /\.tsx?$/.test(entry.name)) sources.push([relative(join(app, 'src'), path), readFileSync(path, 'utf8')]);
        }
    };
    // --check validates committed catalogs, never the ignored localization report.
    if (!check) walk(join(app, 'src'));
    const used = key => sources.filter(([, text]) => text.includes(`'${key.replace(/\.(one|other|few|many|two|zero)$/, '')}'`)).map(([path]) => path).join(', ');
    const rows = buildAppOnlyRows(en, webKeys, used);
    const doc = `# New strings for the localization process\n\nGenerated by \`node scripts/sync-web-i18n.mjs\`. These are the app-only keys in \`apps/mobile/src/lib/i18n/messages/en.ts\`: the public site has no translation for them, so no language is offered for them yet. Placeholders such as \`{count}\` must be kept as written; keys ending in \`.one\` and \`.other\` (and the other CLDR categories) are plural forms.\n\n${rows.length} keys.\n\n| Key | English | Used in |\n|---|---|---|\n${rows.join('\n')}\n`;
    const docPath = join(repo, 'docs', 'mobile', 'I18N-NEW-KEYS.md');
    let docCurrent = '';
    try { docCurrent = readFileSync(docPath, 'utf8'); } catch { /* new file */ }
    if (!check && docCurrent !== doc) { changed.push(relative(repo, docPath)); if (!check) writeFileSync(docPath, doc); }

    if (check && changed.length) { console.error(`Out of date: ${changed.join(', ')}. Run node scripts/sync-web-i18n.mjs`); process.exitCode = 1; return; }
    console.log(check ? 'Up to date.' : `Wrote ${changed.length} file(s).`);

}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    syncWebI18n(process.argv.includes('--check'));
}
