#!/usr/bin/env node
// Website data is read only. Run with --check in CI; regenerate for an app release.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(app, '../..');
const out = join(app, 'src/lib/legal/generated');
const read = async path => import(pathToFileURL(join(repo, path)).href);
const { LEGAL_DOCUMENTS } = await read('lib/i18n/legal/catalogs.mjs');
const { LOCALES } = await read('lib/i18n/locales.mjs');
const { ENTITY } = await import(`data:text/javascript;base64,${Buffer.from(readFileSync(join(repo, 'app/legal/_lib/entity.js'))).toString('base64')}`);
const binding = (await read('lib/i18n/messages/legal/en/binding.mjs')).default;
const check = process.argv.includes('--check');
const header = '// Generated by scripts/sync-web-legal.mjs. Do not edit by hand.\n';
let bytes = 0;
const stale = [];
function emit(name, body) {
    const text = header + body + '\n';
    bytes += Buffer.byteLength(text);
    const path = join(out, name);
    let current = '';
    try { current = readFileSync(path, 'utf8'); } catch { /* first generation */ }
    if (current !== text) {
        stale.push(name);
        if (!check) { mkdirSync(out, { recursive: true }); writeFileSync(path, text); }
    }
}
const documents = {};
for (const doc of LEGAL_DOCUMENTS) {
    const structure = await read(`lib/i18n/legal/${doc}.mjs`);
    documents[doc] = { blocks: structure.default, updated: structure.updated };
}
emit('structure.ts', `export default ${JSON.stringify({ documents, entity: ENTITY, supply: binding.supply })};`);
for (const locale of LOCALES) {
    const documents = {};
    for (const doc of LEGAL_DOCUMENTS) documents[doc] = (await read(`lib/i18n/messages/legal/${locale.code}/${doc}.mjs`)).default;
    const chrome = (await read(`lib/i18n/messages/legal/${locale.code}/chrome.mjs`)).default;
    const jurisdiction = (await read(`lib/i18n/messages/${locale.code}.mjs`)).default['legal.jurisdiction'];
    emit(`${locale.code}.ts`, `export default ${JSON.stringify({ documents, chrome, jurisdiction, tag: locale.hreflang })};`);
}
// Literal requires let Metro discover all assets, but only evaluate the selected locale on demand.
emit('loaders.ts', `export const loaders = {\n${LOCALES.map(l => `    ${l.code}: () => require('./${l.code}').default,`).join('\n')}\n};`);
if (check && stale.length) { console.error(`Stale legal bundle: ${stale.join(', ')}. Run node scripts/sync-web-legal.mjs`); process.exitCode = 1; }
else console.log(`Legal bundle ${check ? 'up to date' : 'generated'}: ${bytes} bytes across ${LOCALES.length} locales (Metro includes all locales; evaluation is lazy).`);
