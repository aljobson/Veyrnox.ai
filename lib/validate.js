const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const UUID_LOOSE_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

// Keep RegExp.test coercion: boundary callers retain their own type guards.
export const isUuid = value => UUID_RE.test(value);
export const isUuidLoose = value => UUID_LOOSE_RE.test(value);
