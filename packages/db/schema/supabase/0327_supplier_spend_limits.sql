-- Supplier-spend circuit breaker.
--
-- Credits and request-rate limits protect customers, but neither bounds the
-- wholesale bill when a funded account or valid session is automated. Every
-- DEBITED job now reserves the catalog's worst-case supplier cost in the same
-- transaction that creates the job. A single locked policy row makes the
-- hourly and UTC-day checks strict across concurrent users and Workers.
--
-- Refunds deliberately do not release reservations: accepted provider work
-- can still be billed after Veyrnox refunds the customer. Replays create no
-- row because the existing job is returned before another INSERT. The public
-- pre-admission RPC lets Chat reserve before its separately billed web search.

CREATE TABLE IF NOT EXISTS public.provider_spend_policy (
    singleton BOOLEAN PRIMARY KEY DEFAULT true CHECK (singleton),
    admission_open BOOLEAN NOT NULL DEFAULT true,
    max_job_microusd BIGINT NOT NULL CHECK (max_job_microusd BETWEEN 1 AND 100000000),
    user_hour_microusd BIGINT NOT NULL CHECK (user_hour_microusd >= max_job_microusd),
    user_day_microusd BIGINT NOT NULL CHECK (user_day_microusd >= user_hour_microusd),
    global_hour_microusd BIGINT NOT NULL CHECK (global_hour_microusd >= user_hour_microusd),
    global_day_microusd BIGINT NOT NULL CHECK (global_day_microusd >= global_hour_microusd),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO public.provider_spend_policy (
    singleton, admission_open, max_job_microusd,
    user_hour_microusd, user_day_microusd,
    global_hour_microusd, global_day_microusd
) VALUES (true, true, 5000000, 15000000, 50000000, 50000000, 250000000)
ON CONFLICT (singleton) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.provider_spend_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    effect_key TEXT NOT NULL CHECK (effect_key ~ '^[A-Za-z0-9._:-]{8,160}$'),
    model_id TEXT NULL,
    provider TEXT NOT NULL CHECK (provider ~ '^[A-Za-z0-9._:-]{2,64}$'),
    purpose TEXT NOT NULL CHECK (purpose ~ '^[a-z0-9._:-]{2,64}$'),
    estimated_cost_microusd BIGINT NOT NULL CHECK (estimated_cost_microusd > 0),
    admitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, effect_key)
);

CREATE INDEX IF NOT EXISTS provider_spend_reservations_hour_idx
    ON public.provider_spend_reservations (admitted_at);
CREATE INDEX IF NOT EXISTS provider_spend_reservations_user_hour_idx
    ON public.provider_spend_reservations (user_id, admitted_at);

