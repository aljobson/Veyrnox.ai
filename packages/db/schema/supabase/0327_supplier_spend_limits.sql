CREATE OR REPLACE FUNCTION private.provider_spend_model_cost(
    p_model_id TEXT, p_inputs JSONB, p_credits INTEGER
) RETURNS TABLE(provider TEXT, purpose TEXT, cost_microusd BIGINT)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE
    v_model public.model_catalog%ROWTYPE;
    v_cost NUMERIC;
    v_units INTEGER;
    v_options JSONB := COALESCE(p_inputs->'options', '{}'::jsonb);
BEGIN
    SELECT * INTO v_model FROM public.model_catalog WHERE id = p_model_id;
    IF NOT FOUND THEN
        -- Older local acceptance tests use a synthetic model. Production
        -- routes require a live catalog row before reaching the ledger; keep
        -- the database backstop conservative if another service does not.
        provider := 'uncatalogued';
        purpose := 'job';
        cost_microusd := GREATEST(1, COALESCE(p_credits, 1))::bigint * 17960;
        RETURN NEXT;
        RETURN;
    END IF;

    provider := v_model.provider;
    purpose := 'job';
    v_units := GREATEST(1, CEIL(GREATEST(1, COALESCE(p_credits, v_model.credits_5s))::numeric
        / v_model.credits_5s)::integer);
    v_cost := v_model.provider_cost_per_unit * v_units;

    -- Text rows record a worst-case base reply plus explicit worst-case
    -- option costs. Research is exclusive; all other options may combine.
    IF v_model.modality = 'text' THEN
        v_cost := v_model.provider_cost_per_unit;
        IF v_options->>'research' = 'true' THEN
            v_cost := v_cost + COALESCE(v_model.chat_research_extra_cost, 0);
        ELSE
            IF v_options->>'thinking' = 'true' THEN
                v_cost := v_cost + COALESCE(v_model.chat_thinking_extra_cost, 0);
            END IF;
            IF v_options->>'web' = 'true' THEN
                v_cost := v_cost + COALESCE(v_model.chat_web_extra_cost, 0);
            END IF;
            IF v_options->>'images' = 'true' THEN
                v_cost := v_cost + COALESCE(v_model.chat_images_extra_cost, 0);
            END IF;
        END IF;
    END IF;

    cost_microusd := CEIL(v_cost * 1000000)::bigint;
    RETURN NEXT;
END $$;

REVOKE ALL ON FUNCTION private.provider_spend_model_cost(TEXT,JSONB,INTEGER) FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION private.provider_spend_reserve(
    p_user_id UUID, p_effect_key TEXT, p_model_id TEXT,
    p_provider TEXT, p_purpose TEXT, p_cost_microusd BIGINT
) RETURNS JSONB
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE
    v_policy public.provider_spend_policy%ROWTYPE;
    v_existing public.provider_spend_reservations%ROWTYPE;
    v_now TIMESTAMPTZ := statement_timestamp();
    v_day_start TIMESTAMPTZ := date_trunc('day', statement_timestamp() AT TIME ZONE 'UTC') AT TIME ZONE 'UTC';
    v_user_hour BIGINT;
    v_user_day BIGINT;
    v_global_hour BIGINT;
    v_global_day BIGINT;
    v_retry INTEGER;
BEGIN
    IF p_user_id IS NULL OR p_effect_key IS NULL OR p_effect_key !~ '^[A-Za-z0-9._:-]{8,160}$'
       OR p_provider IS NULL OR p_provider !~ '^[A-Za-z0-9._:-]{2,64}$'
       OR p_purpose IS NULL OR p_purpose !~ '^[a-z0-9._:-]{2,64}$'
       OR p_cost_microusd IS NULL OR p_cost_microusd <= 0 THEN
        RETURN jsonb_build_object('ok', false, 'code', 'PROVIDER_SPEND_INVALID');
    END IF;

    SELECT * INTO v_existing FROM public.provider_spend_reservations
     WHERE user_id = p_user_id AND effect_key = p_effect_key;
    IF FOUND THEN
        IF v_existing.model_id IS DISTINCT FROM p_model_id
           OR v_existing.provider IS DISTINCT FROM p_provider
           OR v_existing.purpose IS DISTINCT FROM p_purpose
           OR v_existing.estimated_cost_microusd IS DISTINCT FROM p_cost_microusd THEN
            RETURN jsonb_build_object('ok', false, 'code', 'PROVIDER_SPEND_CONFLICT');
        END IF;
        RETURN jsonb_build_object('ok', true, 'idempotent', true,
            'estimated_cost_microusd', v_existing.estimated_cost_microusd);
    END IF;

    -- One row is the global serialization boundary. Missing/closed policy
    -- refuses spend; there is no fail-open mode.
    SELECT * INTO v_policy FROM public.provider_spend_policy WHERE singleton FOR UPDATE;
    IF NOT FOUND OR NOT v_policy.admission_open THEN
        RETURN jsonb_build_object('ok', false, 'code', 'PROVIDER_SPEND_UNAVAILABLE',
            'scope', 'closed', 'retry_after_seconds', 60);
    END IF;
    IF p_cost_microusd > v_policy.max_job_microusd THEN
        RETURN jsonb_build_object('ok', false, 'code', 'PROVIDER_SPEND_LIMIT',
            'scope', 'single', 'retry_after_seconds', 3600);
    END IF;

    SELECT COALESCE(sum(estimated_cost_microusd), 0) INTO v_global_hour
      FROM public.provider_spend_reservations WHERE admitted_at > v_now - interval '1 hour';
    SELECT COALESCE(sum(estimated_cost_microusd), 0) INTO v_global_day
      FROM public.provider_spend_reservations WHERE admitted_at >= v_day_start;
    SELECT COALESCE(sum(estimated_cost_microusd), 0) INTO v_user_hour
      FROM public.provider_spend_reservations
     WHERE user_id = p_user_id AND admitted_at > v_now - interval '1 hour';
    SELECT COALESCE(sum(estimated_cost_microusd), 0) INTO v_user_day
      FROM public.provider_spend_reservations
     WHERE user_id = p_user_id AND admitted_at >= v_day_start;

    IF v_global_hour + p_cost_microusd > v_policy.global_hour_microusd THEN
        SELECT GREATEST(1, CEIL(EXTRACT(epoch FROM (min(admitted_at) + interval '1 hour' - v_now))))::integer
          INTO v_retry FROM public.provider_spend_reservations WHERE admitted_at > v_now - interval '1 hour';
        RETURN jsonb_build_object('ok', false, 'code', 'PROVIDER_SPEND_LIMIT', 'scope', 'global_hour',
            'retry_after_seconds', COALESCE(v_retry, 60));
    END IF;
    IF v_global_day + p_cost_microusd > v_policy.global_day_microusd THEN
        v_retry := GREATEST(1, CEIL(EXTRACT(epoch FROM (v_day_start + interval '1 day' - v_now))))::integer;
        RETURN jsonb_build_object('ok', false, 'code', 'PROVIDER_SPEND_LIMIT', 'scope', 'global_day',
            'retry_after_seconds', v_retry);
    END IF;
    IF v_user_hour + p_cost_microusd > v_policy.user_hour_microusd THEN
        SELECT GREATEST(1, CEIL(EXTRACT(epoch FROM (min(admitted_at) + interval '1 hour' - v_now))))::integer
          INTO v_retry FROM public.provider_spend_reservations
         WHERE user_id = p_user_id AND admitted_at > v_now - interval '1 hour';
        RETURN jsonb_build_object('ok', false, 'code', 'PROVIDER_SPEND_LIMIT', 'scope', 'user_hour',
            'retry_after_seconds', COALESCE(v_retry, 60));
    END IF;
    IF v_user_day + p_cost_microusd > v_policy.user_day_microusd THEN
        v_retry := GREATEST(1, CEIL(EXTRACT(epoch FROM (v_day_start + interval '1 day' - v_now))))::integer;
        RETURN jsonb_build_object('ok', false, 'code', 'PROVIDER_SPEND_LIMIT', 'scope', 'user_day',
            'retry_after_seconds', v_retry);
    END IF;

    INSERT INTO public.provider_spend_reservations
        (user_id, effect_key, model_id, provider, purpose, estimated_cost_microusd, admitted_at)
    VALUES (p_user_id, p_effect_key, p_model_id, p_provider, p_purpose, p_cost_microusd, v_now);
    RETURN jsonb_build_object('ok', true, 'idempotent', false,
        'estimated_cost_microusd', p_cost_microusd);
END $$;

REVOKE ALL ON FUNCTION private.provider_spend_reserve(UUID,TEXT,TEXT,TEXT,TEXT,BIGINT) FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.provider_spend_admit_model(
    p_user_id UUID, p_effect_key TEXT, p_model_id TEXT, p_inputs JSONB, p_credits INTEGER
) RETURNS JSONB
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_cost RECORD;
BEGIN
    IF p_inputs IS NULL OR jsonb_typeof(p_inputs) IS DISTINCT FROM 'object'
       OR octet_length(p_inputs::text) > 16384 OR p_credits IS NULL OR p_credits < 0 THEN
        RETURN jsonb_build_object('ok', false, 'code', 'PROVIDER_SPEND_INVALID');
    END IF;
    SELECT * INTO v_cost FROM private.provider_spend_model_cost(p_model_id, p_inputs, p_credits);
    RETURN private.provider_spend_reserve(p_user_id, p_effect_key, p_model_id,
        v_cost.provider, v_cost.purpose, v_cost.cost_microusd);
END $$;

REVOKE ALL ON FUNCTION public.provider_spend_admit_model(UUID,TEXT,TEXT,JSONB,INTEGER) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.provider_spend_admit_model(UUID,TEXT,TEXT,JSONB,INTEGER) TO service_role;

CREATE OR REPLACE FUNCTION public.provider_spend_admit_custom_auth(
    p_auth_id TEXT, p_effect_key TEXT, p_provider TEXT, p_purpose TEXT, p_cost_microusd BIGINT
) RETURNS JSONB
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_user_id UUID;
BEGIN
    SELECT id INTO v_user_id FROM public.users WHERE auth_id = p_auth_id;
    IF v_user_id IS NULL OR p_cost_microusd > 500000 THEN
        RETURN jsonb_build_object('ok', false, 'code', 'PROVIDER_SPEND_INVALID');
    END IF;
    RETURN private.provider_spend_reserve(v_user_id, p_effect_key, NULL,
        p_provider, p_purpose, p_cost_microusd);
END $$;

REVOKE ALL ON FUNCTION public.provider_spend_admit_custom_auth(TEXT,TEXT,TEXT,TEXT,BIGINT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.provider_spend_admit_custom_auth(TEXT,TEXT,TEXT,TEXT,BIGINT) TO service_role;

CREATE OR REPLACE FUNCTION private.enforce_provider_spend_on_job()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_cost RECORD; v_result JSONB; v_scope TEXT; v_retry INTEGER;
BEGIN
    IF NEW.state::text IS DISTINCT FROM 'DEBITED' THEN RETURN NEW; END IF;
    SELECT * INTO v_cost FROM private.provider_spend_model_cost(NEW.model_id, NEW.inputs, NEW.credits);
    v_result := private.provider_spend_reserve(NEW.user_id, NEW.idempotency_key, NEW.model_id,
        v_cost.provider, v_cost.purpose, v_cost.cost_microusd);
    IF v_result->>'ok' IS DISTINCT FROM 'true' THEN
        v_scope := COALESCE(v_result->>'scope', lower(COALESCE(v_result->>'code', 'unavailable')));
        v_retry := GREATEST(1, LEAST(86400, COALESCE((v_result->>'retry_after_seconds')::integer, 60)));
        RAISE EXCEPTION 'PROVIDER_SPEND_LIMIT:%:%', v_scope, v_retry USING ERRCODE = 'P0001';
    END IF;
    RETURN NEW;
END $$;

REVOKE ALL ON FUNCTION private.enforce_provider_spend_on_job() FROM PUBLIC, anon, authenticated, service_role;
DROP TRIGGER IF EXISTS jobs_provider_spend_guard ON public.jobs;
CREATE TRIGGER jobs_provider_spend_guard
BEFORE INSERT ON public.jobs FOR EACH ROW EXECUTE FUNCTION private.enforce_provider_spend_on_job();

