#!/usr/bin/env node
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { ALL_TEMPLATES } from '../app/veyrnox/_lib/templates.js';
import { SHOWCASE_CLIPS } from '../app/veyrnox/_lib/showcase.js';
import { MODELS, modelIdForName } from '../app/veyrnox/_lib/tokens.js';

export function registryEntries(templates = ALL_TEMPLATES, showcase = SHOWCASE_CLIPS) {
  const entries = templates.flatMap(p => {
    const video = showcase[p.clipKey]?.video;
    const model = MODELS.find(m => m.id === modelIdForName(p.model));
    if (model?.kind !== 'video' || !/^\/showcase\/[a-zA-Z0-9_-]+\.mp4$/.test(video || '')) return [];
    return [[p.id, video.slice('/showcase/'.length)]];
  }).sort(([a], [b]) => a.localeCompare(b, 'en'));
  if (new Set(entries.map(([id]) => id)).size !== entries.length) throw Error('duplicate_template_id');
  return entries;
}
export function renderRegistry() {
  const entries = registryEntries();
  const lines = [];
  for (let i = 0; i < entries.length; i += 3) lines.push('  ' + entries.slice(i, i + 3).map(e => JSON.stringify(e)).join(', ') + ',');
  return `// GENERATED by scripts/gen-template-clip-registry.mjs. No catalog imports in the Worker graph.
export const TEMPLATE_CLIP_MODELS = Object.freeze({
  'seedance-2.0-reference': 'bytedance/seedance-2.0/reference-to-video',
  'seedance-2.0-reference-kie': 'market:bytedance/seedance-2',
});
export function isTemplateClipModel(id) {
  return typeof id === 'string' && Object.hasOwn(TEMPLATE_CLIP_MODELS, id);
}
export const TEMPLATE_CLIPS = Object.freeze([
${lines.join('\n')}
].map(([id, previewFile]) => Object.freeze({ id, previewFile })));

export function publicTemplateClip(id, clips = TEMPLATE_CLIPS) {
  if (typeof id !== 'string' || !/^[a-z0-9][a-z0-9-]{0,127}$/.test(id)) return null;
  const clip = clips.find(item => item.id === id);
  // Preserve the public projection; recast describes the operation, not eligibility.
  return clip ? { id: clip.id, name: clip.id.split('-').map(word => word[0].toUpperCase() + word.slice(1)).join(' '), kind: 'recast' } : null;
}
`;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(new URL('../app/veyrnox/_lib/templateClips.js', import.meta.url), renderRegistry());
}
